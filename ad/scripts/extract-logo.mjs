// Copies the exact logo geometry out of the brand SVGs into src/scene/logo-data.js, so the 3D
// logo is extruded from the real paths rather than redrawn. Run again if the brand files change.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = new URL('../../public/brand/', import.meta.url)
const mark = readFileSync(new URL('mark.svg', root), 'utf8')
const lockup = readFileSync(new URL('lockup-dark.svg', root), 'utf8')

const one = (re, s, what) => {
  const m = s.match(re)
  if (!m) throw new Error(`logo: could not find ${what}`)
  return m
}

// Mark: the evenodd Q body, the tail slab, and the stroke width of the gap mask.
const markBody = one(/<path d="([^"]+)" fill="url\(#qm-face\)" fill-rule="evenodd"/, mark, 'mark body')[1]
const markGap = one(/<mask id="qm-gap"[\s\S]*?<path d="([^"]+)"[^>]*stroke-width="([\d.]+)"/, mark, 'mark gap')
const markTail = markGap[1]

// Wordmark: the letter paths (with fill rules), the Q's tail slab, the gap, and its placement.
const letterGroup = one(/<g fill="url\(#lw-face\)">([\s\S]*?)<\/g>/, lockup, 'wordmark letters')[1]
const letters = [...letterGroup.matchAll(/<path d="([^"]+)" fill-rule="(\w+)"/g)].map((m) => ({
  d: m[1],
  rule: m[2],
}))
const wordGap = one(/<mask id="lw-gap"[\s\S]*?<path d="([^"]+)"[^>]*stroke-width="([\d.]+)"/, lockup, 'wordmark gap')
const wordPlace = one(/<g transform="translate\(([\d.]+) ([\d.]+)\) scale\(([\d.]+)\)">/, lockup, 'wordmark transform')
const markScale = Number(one(/<g transform="scale\(([\d.]+)\)">/, lockup, 'mark scale')[1])
const viewBox = one(/viewBox="0 0 ([\d.]+) ([\d.]+)"/, lockup, 'lockup viewBox')

const data = {
  mark: { body: markBody, tail: markTail, gap: Number(markGap[2]), size: 512 },
  wordmark: { letters, tail: wordGap[1], gap: Number(wordGap[2]) },
  lockup: {
    width: Number(viewBox[1]),
    height: Number(viewBox[2]),
    markScale,
    word: { x: Number(wordPlace[1]), y: Number(wordPlace[2]), scale: Number(wordPlace[3]) },
  },
}

const out = fileURLToPath(new URL('../src/scene/logo-data.js', import.meta.url))
writeFileSync(
  out,
  `// Generated by scripts/extract-logo.mjs from public/brand/*.svg. Do not edit.\nexport default ${JSON.stringify(data, null, 2)}\n`,
)
console.log(`wrote ${out}: ${letters.length} letters, mark gap ${data.mark.gap}, word gap ${data.wordmark.gap}`)
